# 7. Persistent Proxy-Aware HTTPX Client to translate.googleapis.com + SQLite Cache
import os
import ssl
import httpx

_TLS = threading.local()


def create_httpx_kwargs(timeout: float = 12.0) -> Dict[str, object]:
    """Builds portable httpx Client/AsyncClient kwargs honoring HTTPS_PROXY without tripping on [::1] in NO_PROXY."""
    proxy = os.environ.get("HTTPS_PROXY") or os.environ.get("https_proxy") or os.environ.get("HTTP_PROXY") or os.environ.get("http_proxy") or None
    ca_file = os.environ.get("SSL_CERT_FILE") or os.environ.get("REQUESTS_CA_BUNDLE")
    verify_ctx: object = True
    if ca_file and os.path.exists(ca_file):
        verify_ctx = ssl.create_default_context(cafile=ca_file)
    kwargs: Dict[str, object] = {
        "timeout": timeout,
        "follow_redirects": True,
        "trust_env": False,
        "verify": verify_ctx,
        "headers": {
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AlBahithHadithiUrdu/1.0",
            "Referer": "https://hadeeth.com/",
        },
    }
    if proxy:
        kwargs["proxy"] = proxy
    return kwargs


def _raw_google_translate_ar_to_ur(text_ar: str, max_retries: int = 3) -> str:
    if not text_ar or not text_ar.strip():
        return ""
    chunks: List[str] = []
    curr = ""
    for part in re.split(r"(?<=[.۔!\n؛])\s+", text_ar.strip()):
        if len(curr) + len(part) + 1 <= 1750:
            curr = f"{curr} {part}".strip() if curr else part
        else:
            if curr:
                chunks.append(curr)
            curr = part[:1750]
    if curr:
        chunks.append(curr)

    out_chunks: List[str] = []
    for ch in chunks[:6]:
        url = f"https://translate.googleapis.com/translate_a/single?client=gtx&sl=ar&tl=ur&dt=t&q={quote(ch)}"
        piece = ""
        for attempt in range(1, max_retries + 1):
            client: Optional[httpx.Client] = getattr(_TLS, "gt_client", None)
            if client is None:
                client = httpx.Client(**create_httpx_kwargs(timeout=10.0))
                _TLS.gt_client = client
            try:
                resp = client.get(url)
                if resp.status_code == 200:
                    data = resp.json()
                    if isinstance(data, list) and data and isinstance(data[0], list):
                        piece = "".join(
                            seg[0] for seg in data[0] if isinstance(seg, list) and seg and seg[0]
                        )
                    break
                else:
                    client.close()
                    _TLS.gt_client = None
                    time.sleep(0.2 * attempt)
            except Exception:
                try:
                    if client:
                        client.close()
                except Exception:
                    pass
                _TLS.gt_client = None
                time.sleep(0.2 * attempt)
        out_chunks.append(piece)
    return " ".join(x for x in out_chunks if x).strip()



def translate_ar_to_salafi_urdu(
    text_ar: str,
    conn: Optional[sqlite3.Connection] = None,
    rawi_ar: str = "",
    kind: str = "matn",
) -> str:
    """
    Translates any Arabic Hadith matn, Sharh, Biography, or Mustalah passage into dignified Salafi Urdu,
    preserving vocalized Quranic citations inside ﴿...﴾, enforcing strict Salafi terminology,
    and caching permanently in SQLite `urdu_translation_cache`.
    """
    cleaned = strip_html_tags(DORAR_URL_RE.sub("", text_ar or "")).strip()
    if not cleaned:
        return ""

    h_key = hashlib.sha1(f"{kind}:{rawi_ar}:{cleaned[:2500]}".encode("utf-8")).hexdigest()
    if conn is not None:
        from backend.cloud_storage_bridge import get_cached_translation

        cached_ur = get_cached_translation(conn, h_key)
        if cached_ur:
            return cached_ur

    quran_map: Dict[str, str] = {}
    q_idx = 0

    def _q_sub(m: re.Match) -> str:
        nonlocal q_idx
        q_idx += 1
        ayah_ar = m.group(1).strip()
        ref_ar = (m.group(2) or "").strip()
        tok = f"__Q{q_idx}__"
        quran_map[tok] = f"﴿{ayah_ar}﴾ {ref_ar}".strip()
        return f"{tok} ({ayah_ar})"

    prepped = QURAN_BRACKET_RE.sub(_q_sub, cleaned)
    bare = strip_tashkeel(prepped)
    bare = re.sub(r"صلى الله عليه وسلم", "ﷺ", bare)
    if kind == "sharh":
        bare = re.sub(r"وفي الحديث\s*:", "\n\n◈ فقہی و عقدی فوائد:\n۱۔ ", bare)
        bare = re.sub(r"وفيه\s*:", "\n۲۔ ", bare)

    raw_ur = _raw_google_translate_ar_to_ur(bare)
    if not raw_ur:
        return ""

    out = raw_ur
    for tok, q_ar in quran_map.items():
        out = out.replace(tok, f"{q_ar} — ترجمہ:")
        out = out.replace(tok.lower(), f"{q_ar} — ترجمہ:")

    out = sanitize_salafi_urdu(out)
    if kind == "matn" and rawi_ar:
        hon = format_rawi_urdu(rawi_ar)
        if hon and not out.startswith(("سیدنا", "سیدہ", "ام المومنین", "امیر المومنین")):
            out = f"{hon} سے روایت ہے: {out}"
    out = to_ur_digits(out)

    if conn is not None and out:
        from backend.cloud_storage_bridge import save_cached_translation

        save_cached_translation(conn, h_key, cleaned[:4000], out, kind)
    return out
