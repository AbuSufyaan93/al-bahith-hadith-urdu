def translate_fawaz_grades(grades: List[dict], collection_slug: str) -> Tuple[List[dict], str, str, str]:
    """Converts Fawaz CDN English grades list into bilingual Arabic+Salafi Urdu grades."""
    if collection_slug == "bukhari":
        return (
            [{"scholar_ar": "الإمام البخاري", "scholar_ur": "امام بخاری رحمہ اللہ", "grade_ar": "صحيح", "grade_ur": "صحیح (اصح الکتب بعد کتاب اللہ)", "class": "ok"}],
            "صحيح",
            "صحیح (صحیح البخاری)",
            "ok",
        )
    if collection_slug == "muslim":
        return (
            [{"scholar_ar": "الإمام مسلم", "scholar_ur": "امام مسلم رحمہ اللہ", "grade_ar": "صحيح", "grade_ur": "صحیح (صحیح مسلم)", "class": "ok"}],
            "صحيح",
            "صحیح (صحیح مسلم)",
            "ok",
        )
    out = []
    prim_ar, prim_ur, prim_cls = "", "", "ok"
    for item in grades or []:
        name_en = (item.get("name") or "").strip()
        grade_en = (item.get("grade") or "").strip()
        if not grade_en:
            continue
        sch_ur = EN_SCHOLAR_URDU.get(name_en, name_en)
        g_ur, g_ar, g_cls = grade_en, grade_en, "warn"
        for pat_en, u_lbl, a_lbl, c_lbl in EN_GRADE_URDU:
            if pat_en.lower() in grade_en.lower():
                g_ur, g_ar, g_cls = u_lbl, a_lbl, c_lbl
                break
        out.append({
            "scholar_en": name_en,
            "scholar_ur": sch_ur,
            "grade_en": grade_en,
            "grade_ar": g_ar,
            "grade_ur": g_ur,
            "class": g_cls,
        })
        # Prefer Al-Albani or Zubair Ali Zai as primary displayed grade
        if not prim_ur or name_en in ("Al-Albani", "Zubair Ali Zai"):
            prim_ar, prim_ur, prim_cls = g_ar, f"{g_ur} ({sch_ur})", g_cls
    return (out, prim_ar or "غير مصنف", prim_ur or "تحقیق طلب", prim_cls)


