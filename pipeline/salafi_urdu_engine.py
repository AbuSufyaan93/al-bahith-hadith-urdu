def classify_and_translate_grade(grade_ar: str) -> Tuple[str, int, str]:
    """
    Classifies an Arabic hadith ruling into:
      - grade_ur: Dignified Salafi Urdu translation of the ruling
      - grade_bucket: 1 (Authentic Matn), 2 (Authentic Isnad), 3 (Weak/Fabricated Matn), 4 (Weak Isnad), 0 (Other)
      - grade_class: 'ok' | 'warn' | 'bad'
    """
    g = strip_html_tags(strip_tashkeel(grade_ar or "")).strip()
    if not g:
        return ("غیر مصنف", 0, "warn")

