def sanitize_salafi_urdu(text: str) -> str:
    """Applies strict Salafi creed & honorifics sanitization to any Urdu text."""
    if not text:
        return ""
    out = text.strip()
    for pat, repl in SALAFI_POST_RULES:
        out = pat.sub(repl, out)
    out = re.sub(r"[\u0900-\u097F]+", "", out)
    out = re.sub(r"[ \t]{2,}", " ", out)
    return out.strip()


def is_genuine_urdu(text: str) -> bool:
    """Checks whether text contains real Urdu syntax/letters rather than untranslated Arabic."""
    if not text or len(text.strip()) < 15:
        return False
    # Strip leading narrator prefix ("سیدنا ... رضی اللہ عنہ سے روایت ہے:") before checking body
    body = re.sub(r"^[^:]{5,90}:\s*", "", text.strip())
    if len(body) < 10:
        return False
    return len(URDU_STRICT_CHARS_RE.findall(body)) >= 3


def format_rawi_urdu(rawi_ar: str) -> str:
    r = strip_tashkeel((rawi_ar or "").strip())
    if not r or "لا يوجد" in r or r == "الجميع":
        return ""
    if r in FEMALE_COMPANIONS:
        return FEMALE_COMPANIONS[r]
    if r in MALE_OR_DUAL_COMPANIONS:
        return MALE_OR_DUAL_COMPANIONS[r]
    # Check partial match on famous companions
    for k, v in FEMALE_COMPANIONS.items():
        if r == k or r.startswith(k + " "):
            return v
    for k, v in MALE_OR_DUAL_COMPANIONS.items():
        if r == k or r.startswith(k + " "):
            return v
    is_female = (
        r.startswith("أم ")
        or " بنت " in r
        or (r.endswith("ة") and r not in MALE_TAA_EXCEPTIONS and not r.startswith("أبو ") and not r.startswith("ابن "))
    )
    r_ur = r.replace("ك", "ک").replace("ي", "ی").replace("ة", "ہ").replace("ه", "ہ")
    if is_female:
        return f"سیدہ {r_ur} رضی اللہ عنہا"
    return f"سیدنا {r_ur} رضی اللہ عنہ"


